// كاتب ملفات Excel (.xlsx) بسيط بدون مكتبات خارجية
const zlib = require('node:zlib');

const esc = (s) => String(s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')
  // إزالة محارف التحكم غير المسموح بها في XML
  .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, '');

function colName(i) {
  let s = '';
  for (i += 1; i > 0; i = Math.floor((i - 1) / 26)) s = String.fromCharCode(65 + ((i - 1) % 26)) + s;
  return s;
}

function sheetXml(headers, rows, widths) {
  const cell = (v, r, c, style) => {
    const ref = colName(c) + r;
    if (v === null || v === undefined || v === '') return '';
    if (typeof v === 'number') return `<c r="${ref}"${style}><v>${v}</v></c>`;
    return `<c r="${ref}" t="inlineStr"${style}><is><t xml:space="preserve">${esc(v)}</t></is></c>`;
  };
  const line = (vals, r, style = '') => `<row r="${r}">${vals.map((v, c) => cell(v, r, c, style)).join('')}</row>`;
  const cols = widths.map((w, i) => `<col min="${i + 1}" max="${i + 1}" width="${w}" customWidth="1"/>`).join('');
  return '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
    + '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">'
    + '<sheetViews><sheetView workbookViewId="0" rightToLeft="1"><pane ySplit="1" topLeftCell="A2" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>'
    + `<cols>${cols}</cols>`
    + `<sheetData>${line(headers, 1, ' s="1"')}${rows.map((r, i) => line(r, i + 2)).join('')}</sheetData>`
    + (rows.length ? `<autoFilter ref="A1:${colName(headers.length - 1)}${rows.length + 1}"/>` : '')
    + '</worksheet>';
}

